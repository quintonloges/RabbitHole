import { randomUUID } from 'node:crypto';
import { test, expect } from './auth-fixture';

test('source settings persist gradual archive discovery separately from recent refreshes', async ({ page, request }) => {
  const name = `TEST FIXTURE daily archive ${randomUUID()}`;
  const feed = `https://example.org/source-library/${randomUUID()}/feed.xml?large=true`;
  await page.goto('/admin/settings');
  await expect(page.getByRole('checkbox', { name: 'Discover older content daily', exact: true })).toBeChecked();
  await expect(page.getByRole('spinbutton', { name: 'Older items per day', exact: true })).toHaveValue('3');
  await page.getByLabel('Source name', { exact: true }).fill(name);
  await page.getByLabel('Feed URL', { exact: true }).fill(feed);
  await page.getByLabel('Result limit', { exact: true }).fill('1');
  await page.getByLabel('Older items per day', { exact: true }).fill('2');
  await page.getByText('Archive URL (optional)', { exact: true }).click();
  await page.getByLabel('Archive sitemap or feed URL', { exact: true }).fill(feed);
  await page.getByRole('button', { name: 'Add source', exact: true }).click();
  const row = page.locator('.row-item').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(row).toBeVisible();
  const sources = await (await request.get('/api/sources')).json();
  const source = sources.find((entry: { name: string }) => entry.name === name);
  expect(source).toMatchObject({ backfillEnabled: true, backfillLimit: 2, backfillUrl: feed });
  expect(source).not.toHaveProperty('backfillStateJson');
  try {
    await row.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(row).toContainText('HEALTHY');
    const refreshed = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(refreshed.lastImportedCount).toBe(1);
    await row.getByRole('button', { name: 'Find older now', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Archive backfill finished: 2 items imported.');
    await expect(row.getByLabel(`Older content for ${name}`, { exact: true })).toContainText('2 older items added');
    await expect(row).toContainText('Last checked');
    await expect(row).toContainText('Next check');
    const checked = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(checked).toMatchObject({ lastSuccessAt: refreshed.lastSuccessAt, lastImportedCount: refreshed.lastImportedCount, backfillImportedCount: 2 });
    expect(checked.backfillNextAt).toBeTruthy();
    const jobs = await (await request.get('/api/jobs')).json();
    expect(jobs.find((job: { sourceId: string; kind: string }) => job.sourceId === source.id && job.kind === 'backfill')).toMatchObject({ status: 'completed', imported: 2 });
    const activity = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Recent source activity', exact: true }) });
    await expect(activity).toContainText('Archive backfill');
    await expect(activity).toContainText('Refresh');
    await row.scrollIntoViewIfNeeded();
    await page.screenshot({ path: '.cache/ui-review/backfill-desktop.png' });
    const desktopViewport = page.viewportSize();
    await page.setViewportSize({ width: 390, height: 844 });
    await row.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.screenshot({ path: '.cache/ui-review/backfill-mobile.png' });
    if (desktopViewport) await page.setViewportSize(desktopViewport);
    await page.reload();
    await row.getByRole('button', { name: 'Edit', exact: true }).click();
    await expect(page.getByLabel('Older items per day', { exact: true })).toHaveValue('2');
    await page.getByText('Archive URL (optional)', { exact: true }).click();
    await expect(page.getByLabel('Archive sitemap or feed URL', { exact: true })).toHaveValue(feed);
    await page.getByRole('checkbox', { name: 'Discover older content daily', exact: true }).uncheck();
    await page.getByRole('button', { name: 'Save source', exact: true }).click();
    await expect(row).toContainText('Daily discovery off');
    await expect(row.getByRole('button', { name: 'Find older now', exact: true })).toBeDisabled();
    await page.reload();
    const disabled = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(disabled).toMatchObject({ backfillEnabled: false, backfillLimit: 2, backfillUrl: feed, backfillImportedCount: 2 });
    const stopped = await request.post(`/api/sources/${source.id}/backfill`);
    expect(stopped.ok()).toBe(true);
    expect(await stopped.json()).toMatchObject({ kind: 'backfill', status: 'skipped', imported: 0 });
    expect((await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id).backfillImportedCount).toBe(2);
    await page.getByText(/Browse \d+ suggested sources/).click();
    await page.getByRole('button', { name: 'Distill', exact: true }).click();
    await expect(page.getByRole('checkbox', { name: 'Discover older content daily', exact: true })).toBeChecked();
    await expect(page.getByLabel('Older items per day', { exact: true })).toHaveValue('3');
  } finally { await request.delete(`/api/sources/${source.id}`); }
});

test('keyless YouTube archive imports preserve unknown dates and respect pause and off switches', async ({ page, request }) => {
  const before = await (await request.get('/api/settings')).json();
  const name = `TEST FIXTURE keyless uploads ${randomUUID()}`;
  const created = await request.post('/api/sources', { data: { name, kind: 'youtube', url: 'https://www.youtube.com/channel/UC4sdJIrKWKxymZ5lwVSBzTw', backfillEnabled: true, backfillLimit: 3 } });
  expect(created.ok()).toBe(true);
  const source = await created.json();
  try {
    await page.goto('/admin/settings');
    const row = page.locator('.row-item').filter({ has: page.getByRole('heading', { name, exact: true }) });
    await row.getByRole('button', { name: 'Find older now', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Archive backfill finished: 3 items imported.');
    await expect(row.getByLabel(`Older content for ${name}`, { exact: true })).toContainText('3 older items added');
    const stored = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(stored.backfillFailureCount).toBe(0);
    expect(stored.backfillLastSuccessAt).toBeTruthy();
    expect(stored.lastAttemptAt).toBeNull();
    expect(stored.lastError).toBeNull();
    expect(stored).not.toHaveProperty('backfillStateJson');
    expect(stored).not.toHaveProperty('apiKey');
    const imported = await (await request.get(`/api/items?sourceId=${source.id}`)).json();
    expect(imported.total).toBe(3);
    const undated = imported.items.find((item: { providerId: string }) => item.providerId === 'ytgood00001');
    expect(undated).toBeTruthy();
    expect(undated.publishedAt).toBeNull();
    expect(imported.items.find((item: { providerId: string }) => item.providerId === 'ytgood00002').publishedAt).toMatch(/^2011-01-02/);
    await page.goto(`/admin/library?sourceId=${source.id}`);
    await expect(page.getByText('Date unknown', { exact: true })).toBeVisible();
    await page.goto('/admin/settings');
    await page.getByRole('checkbox', { name: /Pause ingestion/ }).check();
    await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
    await expect(row).toContainText('Ingestion paused');
    for (const action of ['Find older now', 'Check YouTube']) await expect(row.getByRole('button', { name: action, exact: true })).toBeDisabled();
    await page.reload();
    await expect(row.getByRole('button', { name: 'Check YouTube', exact: true })).toBeDisabled();
    expect((await request.post(`/api/sources/${source.id}/backfill`)).ok()).toBe(false);
    expect((await request.post(`/api/sources/${source.id}/backfill-check`)).ok()).toBe(false);
    await request.patch('/api/settings', { data: { ingestionPaused: false } });
    await request.patch(`/api/sources/${source.id}`, { data: { backfillEnabled: false } });
    await page.reload();
    await expect(row).toContainText('Daily discovery off');
    for (const action of ['Find older now', 'Check YouTube']) await expect(row.getByRole('button', { name: action, exact: true })).toBeDisabled();
    expect(await (await request.post(`/api/sources/${source.id}/backfill-check`)).json()).toMatchObject({ status: 'skipped', imported: 0 });
    await request.patch(`/api/sources/${source.id}`, { data: { enabled: false, backfillEnabled: true } });
    await page.reload();
    await expect(row).toContainText('Source off');
    for (const action of ['Find older now', 'Check YouTube']) await expect(row.getByRole('button', { name: action, exact: true })).toBeDisabled();
  } finally {
    await request.patch('/api/settings', { data: { ingestionPaused: before.ingestionPaused } });
    await request.delete(`/api/sources/${source.id}`);
  }
});

test('YouTube archive failure stays visible beside a healthy feed and a check recovers without importing or advancing', async ({ page, request }) => {
  const name = `TEST FIXTURE archive recovery ${randomUUID()}`;
  const created = await request.post('/api/sources', { data: { name, kind: 'youtube', url: 'https://www.youtube.com/channel/UCaaaaaaaaaaaaaaaaaaaaaa', backfillEnabled: true, backfillLimit: 2 } });
  expect(created.ok()).toBe(true);
  const source = await created.json();
  try {
    const refresh = await request.post(`/api/sources/${source.id}/refresh`);
    expect(await refresh.json()).toMatchObject({ status: 'completed', imported: 1 });
    await page.goto('/admin/settings');
    const row = page.locator('.row-item').filter({ has: page.getByRole('heading', { name, exact: true }) });
    await expect(row).toContainText('HEALTHY');
    await row.getByRole('button', { name: 'Find older now', exact: true }).click();
    await expect(row.getByRole('alert')).toContainText('YouTube archive needs attention');
    await expect(row).toContainText('Next retry');
    await expect(row).toContainText('No successful older-content check yet');
    await expect(page.getByRole('alert').filter({ hasText: /YouTube archive needs attention for [0-9]+ active/ })).toBeVisible();
    const failed = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(failed).toMatchObject({ backfillStatus: 'failed', backfillFailureCount: 1, backfillImportedCount: 0, lastError: null });
    expect(failed.lastSuccessAt).toBeTruthy();
    expect(failed.backfillNextAt).toBeTruthy();
    await page.reload();
    await expect(row).toContainText('HEALTHY');
    await expect(row.getByRole('alert')).toContainText('YouTube archive needs attention');
    await row.scrollIntoViewIfNeeded();
    await page.screenshot({ path: '.cache/ui-review/youtube-failure-desktop.png' });
    const desktopViewport = page.viewportSize();
    await page.setViewportSize({ width: 390, height: 844 });
    await row.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.screenshot({ path: '.cache/ui-review/youtube-failure-mobile.png' });
    if (desktopViewport) await page.setViewportSize(desktopViewport);
    const beforeCheck = await (await request.get(`/api/items?sourceId=${source.id}`)).json();
    expect(beforeCheck.total).toBe(1);
    await row.getByRole('button', { name: 'Check YouTube', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('YouTube check passed. No items imported.');
    await expect(row.getByRole('alert')).toHaveCount(0);
    await expect(row).toContainText('Last successful check');
    const recovered = (await (await request.get('/api/sources')).json()).find((entry: { id: string }) => entry.id === source.id);
    expect(recovered).toMatchObject({ backfillFailureCount: 0, backfillImportedCount: 0, lastSuccessAt: failed.lastSuccessAt, lastImportedCount: failed.lastImportedCount });
    expect(recovered.backfillLastSuccessAt).toBeTruthy();
    expect(recovered).not.toHaveProperty('backfillStateJson');
    const afterCheck = await (await request.get(`/api/items?sourceId=${source.id}`)).json();
    expect(afterCheck.items.map((item: { id: string }) => item.id)).toEqual(beforeCheck.items.map((item: { id: string }) => item.id));
    const jobs = await (await request.get('/api/jobs')).json();
    expect(jobs.find((job: { sourceId: string; kind: string }) => job.sourceId === source.id && job.kind === 'backfill-check')).toMatchObject({ status: 'completed', imported: 0 });
    const activity = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Recent source activity', exact: true }) });
    await expect(activity).toContainText('YouTube check');
    await row.getByRole('button', { name: 'Find older now', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Archive backfill finished: 2 items imported.');
    const afterImport = await (await request.get(`/api/items?sourceId=${source.id}`)).json();
    expect(afterImport.total).toBe(3);
    expect(afterImport.items.map((item: { providerId: string }) => item.providerId)).toEqual(expect.arrayContaining(['ytcheck0001', 'ytcheck0002']));
    expect(afterImport.items.find((item: { providerId: string }) => item.providerId === 'ytcheck0001').publishedAt).toBeNull();
  } finally { await request.delete(`/api/sources/${source.id}`); }
});
