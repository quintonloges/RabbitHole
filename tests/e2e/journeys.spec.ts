import { test, expect } from '@playwright/test';
import path from 'node:path';

test.describe.serial('A private curiosity engine with real backend state', () => {
  let first: string;
  let book: string;
  let hole: string;

  test('add a source, import genuine fixture responses, save/read and keep a stable edition', async ({ page, request }) => {
    await page.goto('/settings');
    await page.getByLabel('Items per day', { exact: false }).fill('5');
    await page.getByLabel('Optional practice', { exact: true }).check();
    await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
    await expect.poll(async () => (await (await request.get('/api/settings')).json()).editionSize).toBe(5);
    await page.getByRole('combobox', { name: 'Frontier AI weight', exact: true }).selectOption('4');
    await expect.poll(async () => (await (await request.get('/api/topics')).json()).find((t: {name: string}) => t.name === 'Frontier AI').weight).toBe(4);
    await page.getByLabel('Source name', { exact: true }).fill('TEST FIXTURE source');
    await page.getByLabel('Feed URL', { exact: true }).fill('https://example.org/fixture-feed.xml');
    await page.getByRole('button', { name: 'Add source', exact: true }).click();
    const row = page.locator('.row-item').filter({ has: page.getByRole('heading', { name: 'TEST FIXTURE source', exact: true }) });
    await expect(row).toBeVisible();
    await row.getByRole('button', { name: 'Refresh', exact: true }).click();
    await expect(row.getByText(/HEALTHY/)).toBeVisible();
    const source = (await (await request.get('/api/sources')).json()).find((s: { name: string }) => s.name === 'TEST FIXTURE source');
    await request.post(`/api/sources/${source.id}/refresh`);
    const items = await (await request.get('/api/items')).json();
    expect(items.total).toBe(3);
    first = items.items.find((i: { title: string }) => i.title.includes('Consciousness and machines')).id;
    await page.goto('/');
    await page.getByRole('button', { name: 'New selection' }).click();
    await expect(page.getByRole('link', { name: 'TEST FIXTURE: Consciousness and machines', exact: true })).toBeVisible();
    const before = await (await request.get('/api/discover/today')).json();
    await page.reload();
    const after = await (await request.get('/api/discover/today')).json();
    expect(after.items.map((i: { id: string }) => i.id)).toEqual(before.items.map((i: { id: string }) => i.id));
    await page.getByRole('button', { name: 'Show me a little more', exact: true }).click();
    const more = await (await request.get('/api/discover/today')).json();
    expect(new Set(more.items.map((i: { id: string }) => i.id)).size).toBe(3);
    await page.getByText('Why this?', { exact: true }).first().click();
    await page.goto(`/items/${first}`);
    await expect(page.getByText(/This TEST FIXTURE discusses consciousness/).last()).toBeVisible();
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByRole('button', { name: 'Mark read', exact: true }).first().click();
    await page.reload();
    await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Read', exact: true })).toBeVisible();
    const item = await (await request.get(`/api/items/${first}`)).json();
    expect(item.publishedAt).toContain('2020-06-01');
    expect(item.state.understood).toBe(false);
  });

  test('notes, actual branches, sibling preservation and a saved position', async ({ page, request }) => {
    await page.goto(`/items/${first}`);
    await page.getByLabel('A thought to keep').fill('TEST NOTE: a connection worth returning to');
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    await expect(page.getByText('TEST NOTE: a connection worth returning to', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Follow the rabbit hole', exact: true }).click();
    await expect(page).toHaveURL(/\/holes\/[a-z0-9-]+/);
    hole = page.url().split('/').pop()!;
    await page.getByLabel('Find a real item for this branch').fill('Myth and memory');
    await page.getByRole('button', { name: 'Find sources', exact: true }).click();
    await page.getByRole('button', { name: 'Branch here', exact: true }).last().click();
    await page.getByRole('button', { name: /Back to TEST FIXTURE: Consciousness/ }).click();
    await page.getByLabel('Find a real item for this branch').fill('Architectural tradeoffs');
    await page.getByRole('button', { name: 'Find sources', exact: true }).click();
    await page.getByRole('button', { name: 'Branch here', exact: true }).last().click();
    await page.reload();
    const detail = await (await request.get(`/api/holes/${hole}`)).json();
    expect(detail.nodes).toHaveLength(3);
    const children = detail.nodes.filter((n: { parentId: string | null }) => n.parentId);
    expect(children[0].parentId).toBe(children[1].parentId);
    expect(detail.lastNodeId).toBe(children[1].id);
    await page.getByLabel('Branch with a question').fill('TEST QUESTION: where might this lead?');
    await page.getByRole('button', { name: 'Add question', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'TEST QUESTION: where might this lead?', exact: true })).toBeVisible();
    await page.goto('/search');
    await page.getByLabel('A subject, title, or idea').fill('TEST NOTE');
    await page.getByRole('button', { name: 'Search your collection' }).click();
    await expect(page.getByRole('link', { name: 'TEST FIXTURE: Consciousness and machines', exact: true })).toBeVisible();
    await page.getByText('Filter your collection', { exact: true }).click();
    await page.getByRole('combobox', { name: 'Saved', exact: true }).selectOption('true');
    await page.getByRole('combobox', { name: 'Read', exact: true }).selectOption('true');
    await page.getByLabel('Published from', { exact: true }).fill('2020-06-01');
    await page.getByLabel('Published through', { exact: true }).fill('2020-06-01');
    await page.getByRole('button', { name: 'Search your collection' }).click();
    await expect(page.getByText('1 match', { exact: true })).toBeVisible();
  });

  test('import actual EPUB and PDF, navigate chapters, save progress, preserve originals', async ({ page, request }) => {
    await page.goto('/library');
    await page.getByRole('tab', { name: 'Books & files' }).click();
    await page.getByLabel('Choose a PDF or EPUB').setInputFiles(path.resolve('tests/e2e/fixtures/test-book.epub'));
    await expect(page.getByRole('heading', { name: 'TEST FIXTURE: Private book', exact: true })).toBeVisible({ timeout: 45000 });
    const books = await (await request.get('/api/library/books')).json();
    book = books.find((b: { title: string }) => b.title === 'TEST FIXTURE: Private book').id;
    expect(books[0].status).toBe('ready');
    await page.getByRole('button', { name: 'Sections', exact: true }).click();
    await page.getByRole('link', { name: 'Read', exact: true }).first().click();
    await expect(page.getByText(/This is the first actual chapter/).last()).toBeVisible();
    const sectionId = page.url().split('/').pop()!;
    await page.getByRole('slider').fill('42');
    await page.getByRole('slider').blur();
    await expect.poll(async () => (await (await request.get(`/api/items/${sectionId}`)).json()).state.progress).toBe(0.42);
    await page.reload();
    await expect(page.getByRole('slider')).toHaveValue('42');
    expect((await request.get(`/api/library/books/${book}/file`)).ok()).toBe(true);
    await page.goto('/library');
    await page.getByRole('tab', { name: 'Books & files' }).click();
    await page.getByLabel('Choose a PDF or EPUB').setInputFiles(path.resolve('tests/e2e/fixtures/test-page.pdf'));
    await expect(page.getByRole('heading', { name: 'test-page', exact: true })).toBeVisible({ timeout: 45000 });
    const pdf = (await (await request.get('/api/library/books')).json()).find((b: { fileName: string }) => b.fileName === 'test-page.pdf');
    expect(pdf.status).toBe('ready');
    expect(pdf.pageCount).toBe(1);
    const range = await request.post(`/api/library/books/${pdf.id}/sections`, { data: { title: 'TEST RANGE', startPage: 1, endPage: 1 } });
    expect(range.ok()).toBe(true);
    const duplicate = await request.post('/api/library/books/upload', { multipart: { file: { name: 'test-page.pdf', mimeType: 'application/pdf', buffer: await (await import('node:fs/promises')).readFile('tests/e2e/fixtures/test-page.pdf') } } });
    expect((await duplicate.json()).duplicate).toBe(true);
  });

  test('official media metadata and explicitly imported scholarly results', async ({ page, request }) => {
    await page.goto('/search');
    await page.getByLabel('Public URL', { exact: true }).fill('https://www.youtube.com/watch?v=dQw4w9WgXcQ');
    await page.getByRole('button', { name: 'Import link', exact: true }).click();
    await page.getByRole('link', { name: 'Open item →' }).click();
    await expect(page).toHaveURL(/\/items\/[a-z0-9-]+$/);
    await expect(page.getByRole('heading', { name: 'TEST FIXTURE: Video', exact: true })).toBeVisible();
    expect(await page.locator('iframe').count()).toBe(0);
    await page.route('https://www.youtube-nocookie.com/**', route => route.fulfill({ contentType: 'text/html', body: '<p>TEST FIXTURE PLAYER</p>' }));
    await page.getByRole('button', { name: 'Load player' }).click();
    await expect(page.locator('iframe')).toHaveAttribute('src', /https:\/\/www.youtube-nocookie.com\/embed\/dQw4w9WgXcQ/);
    await page.goto('/search');
    await page.getByLabel('Public URL', { exact: true }).fill('https://soundcloud.com/fixture/track');
    await page.getByRole('button', { name: 'Import link', exact: true }).click();
    await page.getByRole('link', { name: 'Open item →' }).click();
    await expect(page).toHaveURL(/\/items\/[a-z0-9-]+$/);
    await expect(page.getByRole('heading', { name: 'TEST FIXTURE: Track', exact: true })).toBeVisible();
    const track = await (await request.get(`/api/items/${page.url().split('/').pop()}`)).json();
    expect(new URL(track.embedUrl).hostname).toBe('w.soundcloud.com');
    await page.goto('/search');
    await page.getByLabel('A subject, title, or idea').fill('consciousness');
    await page.getByRole('button', { name: 'Search research', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'TEST FIXTURE: A consciousness paper', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Import', exact: true }).click();
    await page.getByRole('link', { name: 'Open item →' }).click();
    await expect(page).toHaveURL(/\/items\/[a-z0-9-]+$/);
    await expect(page.getByRole('heading', { name: 'TEST FIXTURE: A consciousness paper', exact: true })).toBeVisible();
    const paper = await (await request.get(`/api/items/${page.url().split('/').pop()}`)).json();
    expect(paper.doi).toBe('10.1234/rabbithole.fixture');
    expect(paper.publishedAt).toContain('2001-02-03');
    expect(paper.textProvenance).toBe('provider-abstract');
    await expect(page.getByText('DOI: 10.1234/rabbithole.fixture', { exact: false })).toBeVisible();
    await expect(page.locator('.reader-body')).toContainText('This fixture abstract discusses consciousness');
  });

  test('opt-in reflection, self-rating and snooze persist without claiming mastery', async ({ page, request }) => {
    await page.goto('/practice');
    await page.getByRole('combobox', { name: 'Source', exact: true }).selectOption(first);
    await page.getByRole('button', { name: 'Create reflection', exact: true }).click();
    await page.getByText('Reveal source passage', { exact: true }).click();
    await expect(page.locator('blockquote')).toContainText('This TEST FIXTURE discusses consciousness');
    await page.getByRole('button', { name: 'Reflect', exact: true }).first().click();
    await page.getByLabel('What comes to mind?').fill('TEST RESPONSE: I recall an attributed claim about consciousness.');
    await page.getByRole('button', { name: 'Good', exact: true }).click();
    await expect(page.getByText('Nothing due right now')).toBeVisible();
    const prompts = await (await request.get('/api/practice/prompts')).json();
    expect(prompts[0].attempts).toHaveLength(1);
    expect(new Date(prompts[0].dueAt).getTime()).toBeGreaterThan(Date.now());
    expect((await (await request.get(`/api/items/${first}`)).json()).state.understood).toBe(false);
    const snooze = await request.post(`/api/practice/prompts/${prompts[0].id}/attempts`, { data: { response: '', rating: 'skip' } });
    expect(snooze.ok()).toBe(true);
    expect((await snooze.json()).reviews).toBe(1);
    await page.getByRole('combobox', { name: 'Source', exact: true }).selectOption(first);
    await page.getByRole('combobox', { name: 'Prompt kind', exact: true }).selectOption('architecture');
    await page.getByRole('button', { name: 'Create architecture', exact: true }).click();
    await expect(page.getByRole('heading', { name: /What design decision would you make/ })).toBeVisible();
  });

  test('security/failure fallbacks, secret-free export and responsive navigation', async ({ page, request }) => {
    const unsafe = await request.post('/api/items/import-url', { data: { url: 'http://127.0.0.1/private' } });
    expect(unsafe.status()).toBe(400);
    const ai = await request.post(`/api/items/${first}/ai`, { data: { action: 'summary' } });
    expect(ai.status()).toBe(409);
    const broken = await request.post('/api/library/books/upload', { multipart: { file: { name: 'bad.pdf', mimeType: 'application/pdf', buffer: Buffer.from('not a PDF') } } });
    expect(broken.status()).toBe(400);
    const exported = await request.post('/api/export');
    expect(exported.ok()).toBe(true);
    const text = await exported.text();
    expect(text).toContain('TEST NOTE');
    expect(text).not.toMatch(/apiKey|password|storageName/i);
    await page.setViewportSize({ width: 390, height: 844 });
    for (const route of ['/', '/holes', '/library', '/practice', '/search', '/settings']) {
      await page.goto(route);
      await expect(page.locator('h1')).toBeVisible();
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    }
    await page.screenshot({ path: 'test-results/mobile-settings.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/');
    await page.screenshot({ path: 'test-results/desktop-discover.png', fullPage: true });
  });
});
